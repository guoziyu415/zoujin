// {name} → the value; unknown placeholders stay as they are
export const fill = (
  s: string,
  vars: Record<string, string | number>,
): string =>
  s.replace(/\{(\w+)\}/g, (all, k: string) =>
    k in vars ? String(vars[k]) : all,
  );
