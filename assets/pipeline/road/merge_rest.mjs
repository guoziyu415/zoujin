// After the other stops' packs are packed (F-15): move the textures in the roadside key table into road-common
// (../common/roadside.mjs, shared with the river and the village), copy a run segment's layout.runway into its
// scene.json (pack_scene.mjs is an input of the plaza's manifest, so it is not changed for this), and write each
// scene's index and merged layout.
// node merge_rest.mjs <road-common dir> <scene dir template> <pack dir>...
//   scene dir template: where a scene's index and merged layout go, {} = the scene's folder name (road-pass ...)
// - <scene>/index.json: which pack the page loads, by act (the page has no world variables, api-contract 2.8): the
//   packs whose layout says partOf this scene (select.act), and a run segment that stands in for the scene in an act
//   (layout.standsIn: act 2's night road for the pass, the spring and the field road); runway: a run segment.
// - <scene>/scene.json: the layout the backend and build_world read for the scene (places, exits, startSpots and the
//   spots of its packs; run segments that stand in are not part of it).
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { SHARED, share } from "../common/roadside.mjs";

const [COMMON, SCENE_DIR, ...PACK_DIRS] = process.argv.slice(2);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCENES = path.resolve(HERE, "../../scenes");
const write = (d, name, obj) =>
  fs.writeFileSync(path.join(d, name), JSON.stringify(obj, null, 1) + "\n");
const layoutOf = (id) =>
  JSON.parse(fs.readFileSync(path.join(SCENES, id, "layout.json"), "utf8"));

// ---- the shared textures (the same source and the same bytes in every pack) into road-common
const { packs, common } = share(
  PACK_DIRS,
  COMMON,
  "assets/pipeline/road/build_rest.sh (merge_rest.mjs, ../common/roadside.mjs)",
);
for (const p of packs) {
  p.layout = layoutOf(p.scene.sceneId);
  if (p.layout.runway) {
    p.scene.runway = p.layout.runway;
    write(p.dir, "scene.json", p.scene);
  }
}

// ---- each road scene: index (page) and merged layout (backend, build_world)
const NOTE =
  "Generated by assets/pipeline/road/build_rest.sh (merge_rest.mjs) from the packs' layout.json; do not edit by hand.";
const sceneIds = [
  ...new Set(packs.map((p) => p.layout.partOf).filter(Boolean)),
].sort();
const summary = [];
for (const SCENE_ID of sceneIds) {
  const own = packs.filter((p) => p.layout.partOf === SCENE_ID);
  const standIns = packs.filter((p) =>
    p.layout.standsIn?.scenes.includes(SCENE_ID),
  );
  const out = SCENE_DIR.replace("{}", SCENE_ID.replace(/^scene\./, ""));
  fs.rmSync(out, { recursive: true, force: true });
  fs.mkdirSync(out, { recursive: true });
  const entry = (p, act) => ({
    pack: p.scene.sceneId,
    act,
    ...(p.layout.runway ? { runway: true } : {}),
    manifest: `../${p.scene.sceneId}/scene.json`,
  });
  write(out, "index.json", {
    version: 1,
    sceneId: SCENE_ID,
    note: NOTE,
    about:
      "Which pack the page loads for this scene: the one whose act matches the act being played (the page has no world variables, api-contract 2.8). runway: a run segment (F-15) the page plays as a treadmill. manifest is relative to this file.",
    packs: [
      ...own.map((p) => entry(p, p.layout.select.act)),
      ...standIns.map((p) => entry(p, p.layout.standsIn.act)),
    ],
    sharedPacks: [SHARED],
  });
  const spots = {};
  const places = new Map();
  const exits = [];
  for (const p of own) {
    for (const pl of p.scene.places)
      if (!places.has(pl.id)) places.set(pl.id, pl);
    for (const e of p.scene.exits)
      if (!exits.some((x) => x.place === e.place && x.spot === e.spot))
        exits.push(e);
    if (p.layout.defaultPlace !== own[0].layout.defaultPlace)
      throw new Error(`${SCENE_ID}: the packs have different default places`);
    for (const [name, s] of Object.entries(p.scene.spots)) {
      const prev = spots[name];
      if (
        prev &&
        (prev.place !== s.place || (prev.auto === false) !== (s.auto === false))
      )
        throw new Error(
          `${SCENE_ID} spot ${name}: the packs disagree on its place or auto`,
        );
      spots[name] = prev ?? {
        place: s.place,
        ...(s.auto === false ? { auto: false } : {}),
        packs: [],
      };
      spots[name].packs.push(p.scene.sceneId);
    }
  }
  write(out, "scene.json", {
    version: 1,
    sceneId: SCENE_ID,
    note: NOTE,
    about: `The layout of ${SCENE_ID} for the backend and build_world: its packs' places, exits and spots (packs: which pack has the spot). startSpots is the first pack's; startSpotsByAct names each act's. Positions are in each pack's scene.json.`,
    packs: own.map((p) => p.scene.sceneId),
    defaultPlace: own[0].layout.defaultPlace,
    places: [...places.values()],
    exits,
    playerStartSpot: own[0].scene.playerStartSpot,
    startSpots: own[0].scene.startSpots,
    startSpotsByAct: Object.fromEntries(
      own.map((p) => [p.layout.select.act, p.scene.startSpots]),
    ),
    spots,
  });
  summary.push(`${SCENE_ID}: ${own.length + standIns.length} packs`);
}
console.log(
  `merged: road-common ${Object.keys(common.textures).length} textures (${(common.bytes.entry / 1e6).toFixed(2)} MB, hi +${(common.bytes.hiExtra / 1e6).toFixed(2)} MB); ` +
    packs
      .map(
        (p) =>
          `${p.scene.sceneId} own ${(p.scene.bytes.entry / 1e6).toFixed(2)} MB, first visit ${(p.scene.bytes.envStd / 1e6).toFixed(2)} MB`,
      )
      .join("; ") +
    `; ${summary.join(", ")}`,
);
