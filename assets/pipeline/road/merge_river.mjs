// After both river packs are packed (F-10): move the textures they share into the roadside pack road-common, which
// the later stops use too and which is downloaded once, and write scene.road-river's index and merged layout.
// node merge_river.mjs <calm dir> <flood dir> <road-common dir> <road-river dir>
// - road-common/pack.json: the shared textures (their std and hi KTX2 files); not a scene, so not named scene.json
//   (the backend reads every assets/scenes/*/scene.json as a scene layout).
// - each pack's scene.json: those files stay in its file list with `shared: "road-common"` (the path is relative to
//   the shared pack), bytes.entry / hiExtra count the pack's own files, bytes.shared what road-common adds, and
//   envStd / envHi are the first visit with nothing cached (own + shared).
// - road-river/index.json: which pack the page loads, by act (the page has no world variables, api-contract 2.8),
//   with the matching var.bridge value for reference; road-river/scene.json: the layout the backend and build_world
//   read for scene.road-river (places, exits, startSpots and the spots of both packs).
import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const [CALM, FLOOD, COMMON, RIVER] = process.argv.slice(2);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCENES = path.resolve(HERE, "../../scenes");
const SHARED = "road-common";
// homeward-road.md 0.4: the roadside materials every stop has (road, dry grass, limestone, gravel, dry-stone walls
// in the limestone texture, trees and shrubs, the far hills)
const COMMON_STEMS = [
  "road",
  "grass",
  "outcrop",
  "gravel",
  "bark",
  "poplar",
  "holmoak",
  "hill",
];
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const read = (d) =>
  JSON.parse(fs.readFileSync(path.join(d, "scene.json"), "utf8"));
const write = (d, name, obj) =>
  fs.writeFileSync(path.join(d, name), JSON.stringify(obj, null, 1) + "\n");
const packs = [
  { dir: CALM, scene: read(CALM) },
  { dir: FLOOD, scene: read(FLOOD) },
];
const errors = [];

// ---- the shared textures: the same source and the same bytes in both packs
fs.rmSync(COMMON, { recursive: true, force: true });
fs.mkdirSync(COMMON, { recursive: true });
const stemOf = (key) => key.slice(0, key.lastIndexOf("_"));
const sharedKeys = [
  ...new Set(
    packs.flatMap((p) =>
      Object.keys(p.scene.textures).filter((k) =>
        COMMON_STEMS.includes(stemOf(k)),
      ),
    ),
  ),
].sort();
const common = { textures: {}, files: [] };
for (const key of sharedKeys) {
  const have = packs.filter((p) => p.scene.textures[key]);
  const [first] = have;
  const t = first.scene.textures[key];
  for (const p of have.slice(1)) {
    const u = p.scene.textures[key];
    if (
      u.sourceSha256 !== t.sourceSha256 ||
      u.std.file !== t.std.file ||
      u.hi?.file !== t.hi?.file
    )
      errors.push(`${key}: the two packs disagree (source or tiers)`);
  }
  common.textures[key] = t;
  for (const rel of [t.std.file, t.hi?.file].filter(Boolean)) {
    const buf = fs.readFileSync(path.join(first.dir, rel));
    for (const p of have) {
      const f = p.scene.files.find((x) => x.path === rel);
      if (!f || f.sha256 !== sha(buf))
        errors.push(`${rel}: not the same bytes in ${p.scene.sceneId}`);
    }
    fs.mkdirSync(path.dirname(path.join(COMMON, rel)), { recursive: true });
    fs.writeFileSync(path.join(COMMON, rel), buf);
    const f = first.scene.files.find((x) => x.path === rel);
    common.files.push({
      path: rel,
      bytes: f.bytes,
      sha256: f.sha256,
      pack: f.pack,
    });
    for (const p of have) fs.rmSync(path.join(p.dir, rel));
  }
}
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}
common.files.sort((a, b) => (a.path < b.path ? -1 : 1));
const sum = (files, pack) =>
  files.filter((f) => f.pack === pack).reduce((s, f) => s + f.bytes, 0);
const sharedBytes = {
  entry: sum(common.files, "entry"),
  hiExtra: sum(common.files, "hi"),
};
const sharedPaths = new Set(common.files.map((f) => f.path));
write(COMMON, "pack.json", {
  version: 1,
  pack: SHARED,
  note: "Generated by assets/pipeline/road/build.sh (merge_river.mjs); do not edit by hand.",
  about:
    "Roadside textures every stop of the homeward road shares (ux/scenes/homeward-road.md 0.4), downloaded once. A pack's scene.json lists these files with shared: road-common; paths are relative to this pack.",
  usedBy: packs.map((p) => p.scene.sceneId),
  textures: common.textures,
  files: common.files,
  bytes: sharedBytes,
});

// ---- each pack: shared files marked, bytes split into own and shared
for (const p of packs) {
  const s = p.scene;
  s.sharedPacks = [SHARED];
  for (const f of s.files) if (sharedPaths.has(f.path)) f.shared = SHARED;
  for (const k of sharedKeys) if (s.textures[k]) s.textures[k].shared = SHARED;
  const own = s.files.filter((f) => !f.shared);
  s.bytes = {
    entry: sum(own, "entry"),
    hiExtra: sum(own, "hi"),
    shared: sharedBytes,
  };
  s.bytes.envStd = s.bytes.entry + sharedBytes.entry;
  s.bytes.envHi = s.bytes.envStd + s.bytes.hiExtra + sharedBytes.hiExtra;
  write(p.dir, "scene.json", s);
}

// ---- scene.road-river: index (page) and merged layout (backend, build_world)
fs.rmSync(RIVER, { recursive: true, force: true });
fs.mkdirSync(RIVER, { recursive: true });
const layouts = packs.map((p) =>
  JSON.parse(
    fs.readFileSync(path.join(SCENES, p.scene.sceneId, "layout.json"), "utf8"),
  ),
);
const SCENE_ID = layouts[0].partOf;
if (layouts.some((l) => l.partOf !== SCENE_ID))
  throw new Error("the two packs are not parts of the same scene");
const NOTE =
  "Generated by assets/pipeline/road/build.sh (merge_river.mjs) from the two packs' layout.json; do not edit by hand.";
write(RIVER, "index.json", {
  version: 1,
  sceneId: SCENE_ID,
  note: NOTE,
  about:
    "Which pack the page loads for this scene: the one whose act matches the act being played (the page has no world variables, api-contract 2.8). bridge is the world model's var.bridge in that act, for reference (data: act 2 always intact, act 4 always destroyed). manifest is relative to this file.",
  packs: packs.map((p, i) => ({
    pack: p.scene.sceneId,
    act: layouts[i].select.act,
    bridge: layouts[i].select.bridge,
    manifest: `../${p.scene.sceneId}/scene.json`,
  })),
  sharedPacks: [SHARED],
});
const spots = {};
const places = new Map();
const exits = [];
for (const [i, p] of packs.entries()) {
  for (const pl of p.scene.places)
    if (!places.has(pl.id)) places.set(pl.id, pl);
  for (const e of p.scene.exits)
    if (!exits.some((x) => x.place === e.place && x.spot === e.spot))
      exits.push(e);
  for (const [name, s] of Object.entries(p.scene.spots)) {
    const prev = spots[name];
    if (
      prev &&
      (prev.place !== s.place || (prev.auto === false) !== (s.auto === false))
    )
      throw new Error(`spot ${name}: the packs disagree on its place or auto`);
    spots[name] = prev ?? {
      place: s.place,
      ...(s.auto === false ? { auto: false } : {}),
      packs: [],
    };
    spots[name].packs.push(p.scene.sceneId);
    if (layouts[i].defaultPlace !== layouts[0].defaultPlace)
      throw new Error("the packs have different default places");
  }
}
write(RIVER, "scene.json", {
  version: 1,
  sceneId: SCENE_ID,
  note: NOTE,
  about:
    "The layout of scene.road-river for the backend and build_world: both packs' places, exits and spots (packs: which pack has the spot). startSpots is act 2's (the player comes from the east); act 4 arrives at road-west, named by the world model's exit (startSpotsByAct). Positions are in each pack's scene.json.",
  packs: packs.map((p) => p.scene.sceneId),
  defaultPlace: layouts[0].defaultPlace,
  places: [...places.values()],
  exits,
  playerStartSpot: packs[0].scene.playerStartSpot,
  startSpots: packs[0].scene.startSpots,
  startSpotsByAct: Object.fromEntries(
    packs.map((p, i) => [layouts[i].select.act, p.scene.startSpots]),
  ),
  spots,
});
console.log(
  `merged: ${sharedKeys.length} shared textures (${(sharedBytes.entry / 1e6).toFixed(2)} MB, hi +${(sharedBytes.hiExtra / 1e6).toFixed(2)} MB); ` +
    packs
      .map(
        (p) =>
          `${p.scene.sceneId} own ${(p.scene.bytes.entry / 1e6).toFixed(2)} MB, first visit ${(p.scene.bytes.envStd / 1e6).toFixed(2)} MB`,
      )
      .join("; "),
);
