// After both river packs are packed (F-10): move the textures in the roadside key table into road-common
// (../common/roadside.mjs, shared with the village), and write scene.road-river's index and merged layout.
// node merge_river.mjs <calm dir> <flood dir> <road-common dir> <road-river dir>
// - road-river/index.json: which pack the page loads, by act (the page has no world variables, api-contract 2.8),
//   with the matching var.bridge value for reference; road-river/scene.json: the layout the backend and build_world
//   read for scene.road-river (places, exits, startSpots and the spots of both packs).
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { SHARED, share } from "../common/roadside.mjs";

const [CALM, FLOOD, COMMON, RIVER] = process.argv.slice(2);
const HERE = path.dirname(fileURLToPath(import.meta.url));
const SCENES = path.resolve(HERE, "../../scenes");
const write = (d, name, obj) =>
  fs.writeFileSync(path.join(d, name), JSON.stringify(obj, null, 1) + "\n");

// ---- the shared textures (the same source and the same bytes in both packs) into road-common
const { packs, common } = share(
  [CALM, FLOOD],
  COMMON,
  "assets/pipeline/road/build.sh (merge_river.mjs, ../common/roadside.mjs)",
);

// ---- scene.road-river: index (page) and merged layout (backend, build_world)
fs.rmSync(RIVER, { recursive: true, force: true });
fs.mkdirSync(RIVER, { recursive: true });
const layouts = packs.map((p) =>
  JSON.parse(
    fs.readFileSync(path.join(SCENES, p.scene.sceneId, "layout.json"), "utf8"),
  ),
);
const SCENE_ID = layouts[0].partOf;
if (layouts.some((l) => l.partOf !== SCENE_ID))
  throw new Error("the two packs are not parts of the same scene");
const NOTE =
  "Generated by assets/pipeline/road/build.sh (merge_river.mjs) from the two packs' layout.json; do not edit by hand.";
write(RIVER, "index.json", {
  version: 1,
  sceneId: SCENE_ID,
  note: NOTE,
  about:
    "Which pack the page loads for this scene: the one whose act matches the act being played (the page has no world variables, api-contract 2.8). bridge is the world model's var.bridge in that act, for reference (data: act 2 always intact, act 4 always destroyed). manifest is relative to this file.",
  packs: packs.map((p, i) => ({
    pack: p.scene.sceneId,
    act: layouts[i].select.act,
    bridge: layouts[i].select.bridge,
    manifest: `../${p.scene.sceneId}/scene.json`,
  })),
  sharedPacks: [SHARED],
});
const spots = {};
const places = new Map();
const exits = [];
for (const [i, p] of packs.entries()) {
  for (const pl of p.scene.places)
    if (!places.has(pl.id)) places.set(pl.id, pl);
  for (const e of p.scene.exits)
    if (!exits.some((x) => x.place === e.place && x.spot === e.spot))
      exits.push(e);
  for (const [name, s] of Object.entries(p.scene.spots)) {
    const prev = spots[name];
    if (
      prev &&
      (prev.place !== s.place || (prev.auto === false) !== (s.auto === false))
    )
      throw new Error(`spot ${name}: the packs disagree on its place or auto`);
    spots[name] = prev ?? {
      place: s.place,
      ...(s.auto === false ? { auto: false } : {}),
      packs: [],
    };
    spots[name].packs.push(p.scene.sceneId);
    if (layouts[i].defaultPlace !== layouts[0].defaultPlace)
      throw new Error("the packs have different default places");
  }
}
write(RIVER, "scene.json", {
  version: 1,
  sceneId: SCENE_ID,
  note: NOTE,
  about:
    "The layout of scene.road-river for the backend and build_world: both packs' places, exits and spots (packs: which pack has the spot). startSpots is act 2's (the player comes from the east); act 4 arrives at road-west, named by the world model's exit (startSpotsByAct). Positions are in each pack's scene.json.",
  packs: packs.map((p) => p.scene.sceneId),
  defaultPlace: layouts[0].defaultPlace,
  places: [...places.values()],
  exits,
  playerStartSpot: packs[0].scene.playerStartSpot,
  startSpots: packs[0].scene.startSpots,
  startSpotsByAct: Object.fromEntries(
    packs.map((p, i) => [layouts[i].select.act, p.scene.startSpots]),
  ),
  spots,
});
console.log(
  `merged: ${Object.keys(common.textures).length} textures in ${SHARED} (${(common.bytes.entry / 1e6).toFixed(2)} MB, hi +${(common.bytes.hiExtra / 1e6).toFixed(2)} MB); ` +
    packs
      .map(
        (p) =>
          `${p.scene.sceneId} own ${(p.scene.bytes.entry / 1e6).toFixed(2)} MB, first visit ${(p.scene.bytes.envStd / 1e6).toFixed(2)} MB`,
      )
      .join("; "),
);
