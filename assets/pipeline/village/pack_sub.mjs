// The village's light sub-packs (F-11 card 1): sunset, night and rain, lightmaps only, each with a pack.json (not
// scene.json: the backend reads every assets/scenes/*/scene.json as a scene layout); then village/scene.json lists
// every sub-pack (subPacks: these and the interior, ./interior/, by its committed pack.json) and when each light is
// used (lightSets, from layout.json).
// node pack_sub.mjs <work_dir> <layout.json> <village dir>
// Each sub-pack goes beside the village's directory: assets/scenes/<sub>/build for a final build, <out>/<sub> for a
// draft (the same swap as check_scene.mjs makes for road-common).
// A light sub-pack carries the indirect light of the village pack's two lightmapped meshes (ground, arch) for another
// time and weather, on the same lightmap UVs; the AO stays the village pack's.
import crypto from "crypto";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { ktx2 } from "./ktx2.mjs";

const [, , WORK, LAYOUT, VILLAGE] = process.argv;
const STEM = process.env.SCENE_STEM ?? "village";
const layout = JSON.parse(fs.readFileSync(LAYOUT, "utf8"));
const subDir = (pack) => {
  const parts = path.resolve(VILLAGE).split(path.sep);
  parts[parts.at(-1) === "build" ? parts.length - 2 : parts.length - 1] = pack;
  return parts.join(path.sep);
};
const scene = JSON.parse(
  fs.readFileSync(path.join(VILLAGE, "scene.json"), "utf8"),
);
const sha = (b) => crypto.createHash("sha256").update(b).digest("hex");
const json = (f) => JSON.parse(fs.readFileSync(f, "utf8"));
const write = (f, obj) =>
  fs.writeFileSync(f, JSON.stringify(obj, null, 1) + "\n");
const NOTE =
  "Generated by assets/pipeline/village/build.sh (relight.py, pack_sub.mjs); do not edit by hand.";

function packer(pack) {
  const dir = subDir(pack);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(path.join(dir, "lm"), { recursive: true });
  const files = [];
  const put = (rel, buf) => {
    fs.writeFileSync(path.join(dir, rel), buf);
    files.push({ path: rel, bytes: buf.length, sha256: sha(buf), pack: "sub" });
    return rel;
  };
  return { dir, files, put };
}
// a draft bake is smaller: keep its size, as pack_scene.mjs
const lm = async (put, png, res, rel, kind = "color") =>
  put(rel, (await ktx2(fs.readFileSync(png), res, kind)).buf);

const subPacks = [];
// ---------------------------------------------------------------- the light sub-packs
for (const set of ["sunset", "night", "rain"]) {
  const pack = `village-light-${set}`;
  const src = path.join(WORK, `light-${set}`);
  const meta = json(path.join(src, "lm_meta.json"));
  const { dir, files, put } = packer(pack);
  const res = Math.min(scene.lightmaps.res, meta.ground.res, meta.arch.res);
  const lightmaps = { res };
  for (const mesh of ["ground", "arch"])
    lightmaps[mesh] = {
      indirect: {
        file: await lm(
          put,
          path.join(src, `lm_${mesh}_indirect.png`),
          res,
          `lm/${mesh}_indirect.ktx2`,
        ),
        K: meta[mesh].K,
      },
      bakedRes: meta[mesh].res,
    };
  const bytes = files.reduce((s, f) => s + f.bytes, 0);
  write(path.join(dir, "pack.json"), {
    version: 1,
    pack,
    kind: "light",
    of: scene.sceneId,
    note: NOTE,
    about:
      "One light of the village for another time or weather (village.md 5): the indirect light of the village pack's lightmapped meshes (ground, arch) on their lightmap UVs; three.js lightMapIntensity = PI * K as in the village pack. The AO stays the village pack's; the sun (null when there is none) is drawn live; lamps are where the bake had them (glTF metres), for the page's dynamic light.",
    light: set,
    bakeMinute: meta.bakeMinute,
    sky: meta.sky,
    sun: meta.sun,
    lamps: meta.lamps,
    quality: scene.quality,
    lightmaps,
    files,
    bytes: { entry: bytes },
  });
  subPacks.push({ pack, kind: "light", light: set, bytes });
  console.log(`${pack}: ${(bytes / 1e6).toFixed(2)} MB`);
}

// ---------------------------------------------------------------- the interior (its own pipeline, ./interior/)
{
  const REPO = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../../..",
  );
  const mf = path.join(REPO, "assets/scenes/village-interior/pack.json");
  if (fs.existsSync(mf))
    subPacks.push({
      pack: "village-interior",
      kind: "interior",
      bytes: json(mf).bytes,
    });
}

// ---------------------------------------------------------------- village/scene.json
scene.subPacks = subPacks.map(({ pack, kind, light, bytes }) => ({
  pack,
  kind,
  ...(light ? { light } : {}),
  manifest: `../${pack}/pack.json`,
  bytes,
}));
scene.lightSets = layout.lightSets;
// bytes stays the first visit's (own + shared, roadside.mjs packBytes); the sub-packs come after it
scene.subPackBytes = subPacks.reduce((s, p) => s + p.bytes, 0);
write(path.join(VILLAGE, "scene.json"), scene);
