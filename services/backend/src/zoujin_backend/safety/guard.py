"""再確認の前のガードレール（B-15、S-072 ⑤）：一人称で決意、手段、時間、別れを述べた文は、1 回目で signal と判定されたら
再確認せず、そのまま一時停止する。

S-072 ⑤：再確認が「決意を述べた」ような文を下げることは決してあってはならず、1 件でも漏れたら使えない。この関門は
決定的で、モデルはこの種の文の再確認リクエストを見ない。
語彙はメインセットにある実際のシグナルに基づいて決めた（メインセットは公開）。**ホールドアウトは見ない**。多めに止めて
よい：多く止めても誤判定を 1 件下げ損ねるだけだが、止め損ねれば事故になる。
"""

from __future__ import annotations

import re
import unicodedata

# 決意、手段、時間、別れ（ひらがなと漢字の両方の書き方を認める。NFKC の後で比べる）
_DECIDED = re.compile(
    "|".join(
        (
            r"決め(?:た|てる|ている|ました)",
            r"きめ(?:た|てる)",
            r"(?:終わり|おわり|終り)に(?:する|しよう|します|したい)",
            r"終わらせ|おわらせ",
            r"(?:死|し)(?:ぬ|にます)(?:つもり|ことに|気|って)",
            r"(?:死|し)のう",
            r"(?:死|し)にたい",
            r"(?:死|し)んだ方が",
            r"消え(?:たい|る(?:つもり|ことに))",
            r"きえたい",
            r"いなく(?:なりたい|なる(?:つもり|ことに))",
            r"生きて(?:いたくない|いく意味|る意味)",
            r"今夜|今晩|明日の朝",
            r"薬|くすり",
            r"飛び降り|とびおり",
            r"首を(?:吊|つ)",
            r"遺書|いしょ",
            r"さよなら|さようなら",
            r"自分を(?:傷|切|刺)",
            r"手首|リスカ|練炭|線路|ロープ|刃物|屋上",
            # メインセットで「決意を述べた」ものではないが、本人の気持ちがはっきり述べられている書き方（これも
            # 再確認しない）
            r"消えて(?:しまい|ちゃい)たい",
            r"目が覚めなければ|朝なんて来なければ",
            r"いなくなった(?:ほう|方)が",
            r"今までありがとう",
            r"生きてる(?:の)?が(?:つらい|辛い|しんどい)",
            r"希死念慮",
            r"(?i:\b(?:alive|suicide|kill myself|die|end it)\b)",
        )
    )
)


def decided(text: str) -> bool:
    """この文に決意、手段、時間、別れを述べた書き方があるか（一致 = 再確認しない）。"""
    return _DECIDED.search(unicodedata.normalize("NFKC", text)) is not None
