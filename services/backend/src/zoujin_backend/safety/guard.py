"""复核之前的护栏（B-15，S-072 ⑤）：一人称说出决定、手段、时间、告别的句子，第一遍判成 signal 就不复核，直接暂停。

S-072 ⑤：复核绝不能把「说出决定」这类降下来，漏一条就不用。这一关是确定性的，模型看不到这类句子的复核请求。
词表按主集里的真实信号定（主集是开的）；**不看留出**。宁可多挡：多挡只是少降一条误判，漏挡才是事故。
"""

from __future__ import annotations

import re
import unicodedata

# 决定、手段、时间、告别（平假名和汉字两种写法都认；NFKC 以后比）
_DECIDED = re.compile(
    "|".join(
        (
            r"決め(?:た|てる|ている|ました)",
            r"きめ(?:た|てる)",
            r"(?:終わり|おわり|終り)に(?:する|しよう|します|したい)",
            r"終わらせ|おわらせ",
            r"(?:死|し)(?:ぬ|にます)(?:つもり|ことに|気|って)",
            r"(?:死|し)のう",
            r"(?:死|し)にたい",
            r"(?:死|し)んだ方が",
            r"消え(?:たい|る(?:つもり|ことに))",
            r"きえたい",
            r"いなく(?:なりたい|なる(?:つもり|ことに))",
            r"生きて(?:いたくない|いく意味|る意味)",
            r"今夜|今晩|明日の朝",
            r"薬|くすり",
            r"飛び降り|とびおり",
            r"首を(?:吊|つ)",
            r"遺書|いしょ",
            r"さよなら|さようなら",
            r"自分を(?:傷|切|刺)",
            r"手首|リスカ|練炭|線路|ロープ|刃物|屋上",
            # 主集里不是「说出决定」、但本人的心情说得很清楚的写法（也不复核）
            r"消えて(?:しまい|ちゃい)たい",
            r"目が覚めなければ|朝なんて来なければ",
            r"いなくなった(?:ほう|方)が",
            r"今までありがとう",
            r"生きてる(?:の)?が(?:つらい|辛い|しんどい)",
            r"希死念慮",
            r"(?i:\b(?:alive|suicide|kill myself|die|end it)\b)",
        )
    )
)


def decided(text: str) -> bool:
    """这句话里有没有说出决定、手段、时间、告别的写法（命中 = 不复核）。"""
    return _DECIDED.search(unicodedata.normalize("NFKC", text)) is not None
