"""World models and scene layouts (read-only).

- World model: `worlds/<bookId>/<version dir>/world.json`, looked up by `worldModelVersion`; a game locks its version
  when it starts (data-design 4.5). Which one new games use is set by configuration (`ZJ_WORLD`; the draft if unset),
  not by directory order.
- Scene layout: `defaultPlace`, `places`, `spots`, `exits` and `startSpots` of `assets/scenes/<scene>/scene.json`
  (generated by the frontend pipeline). Spots can only be projected for scenes that have a layout; for scenes without
  one yet, the spot is the last segment of the place ID.

世界モデルと場面レイアウト（読み取り専用）。

- 世界モデル：`worlds/<bookId>/<バージョンディレクトリ>/world.json`、`worldModelVersion` で探す。
  ゲーム開始時にバージョンを固定する（data-design 4.5）。新しいゲームでどれを使うかは設定で決め
  （`ZJ_WORLD`、未設定なら草稿）、ディレクトリの並び順では決めない。
- 場面レイアウト：`assets/scenes/<場面>/scene.json`（フロントエンドのパイプラインが生成）の `defaultPlace`、`places`、
  `spots`、`exits`、`startSpots`。レイアウトのある場面だけ立ち位置を投影できる。レイアウトがまだない場面では、
  立ち位置は場所 ID の最後の部分を使う。
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import cached_property
from pathlib import Path
from typing import Any

from zoujin_worldsim import Sim

from zoujin_backend.clock import Labels

Json = Any


@dataclass(frozen=True)
class Scene:
    scene_id: str
    places: tuple[str, ...]  # the first one is defaultPlace / 先頭が defaultPlace
    spots: dict[str, str]  # spot → place, in layout order / 立ち位置 → 場所、レイアウトの順
    exits: tuple[dict[str, str], ...]  # {place, spot}
    start_spots: dict[str, str]  # place → the spot the player stands on / 場所 → プレイヤーの立ち位置
    # Spots with `auto: false`: only assigned explicitly by beats and ending set pieces; auto-assignment skips them.
    # `auto: false` の立ち位置：ビートやエンディングの演出が明示的に指定するときだけ使い、自動割り当てでは飛ばす。
    manual: frozenset[str] = frozenset()

    @classmethod
    def read(cls, path: Path) -> Scene:
        d = json.loads(path.read_text(encoding="utf-8"))
        places = [d["defaultPlace"], *(p["id"] for p in d.get("places", []) if p["id"] != d["defaultPlace"])]
        return cls(
            scene_id=d["sceneId"],
            places=tuple(places),
            spots={k: v["place"] for k, v in d.get("spots", {}).items()},
            exits=tuple({"place": e["place"], "spot": e["spot"]} for e in d.get("exits", [])),
            start_spots=dict(d.get("startSpots", {})),
            manual=frozenset(k for k, v in d.get("spots", {}).items() if v.get("auto") is False),
        )

    def auto_spots(self, place: str) -> list[str]:
        """Spots usable for automatic assignment (layout order): this place's, except `way.*` and `auto: false` ones.

        自動割り当てに使える立ち位置（レイアウト順）：この場所のもので、`way.*` と `auto: false` のものを除く。
        """
        return [s for s, p in self.spots.items() if p == place and not s.startswith("way.") and s not in self.manual]

    def player_spot(self, place: str) -> str:
        if place in self.start_spots:
            return self.start_spots[place]
        return next(iter(self.auto_spots(place)), _slug(place))

    def character_spots(self, people: list[tuple[str, str]], taken: set[str] | None = None) -> dict[str, str]:
        """Characters take, in order, the free spots of their place (those in `auto_spots` not in taken). taken holds
        the player's spot, so characters don't stand on the player; when spots run out they overlap with other
        characters on the first spot, and overlap with the player only when the player's spot is the place's only one.

        登場人物は順に自分の場所の空いている立ち位置（`auto_spots` のうち taken 以外）を取る。taken には
        プレイヤーの立ち位置を渡し、登場人物がプレイヤーに重ならないようにする。足りなければ最初の立ち位置で
        ほかの登場人物と重なり、その場所にプレイヤーの立ち位置しかないときだけプレイヤーと重なる。
        """
        player = set(taken or ())
        taken = set(player)
        out: dict[str, str] = {}
        for who, place in people:
            usable = self.auto_spots(place)
            free = [s for s in usable if s not in taken]
            spot = free[0] if free else next((s for s in usable if s not in player), next(iter(usable), _slug(place)))
            taken.add(spot)
            out[who] = spot
        return out


def _slug(place_id: str) -> str:
    return place_id.removeprefix("place.")


@dataclass
class Book:
    """One world model version of one book.

    1 冊の本の、1 つの世界モデルバージョン。
    """

    book_id: str
    world: Json
    scenes: dict[str, Scene] = field(default_factory=dict)
    path: Path | None = None  # world.json, the file named in errors / world.json、エラー時に示すファイル

    @property
    def version(self) -> str:
        v: str = self.world["worldModelVersion"]
        return v

    @cached_property
    def labels(self) -> Labels:
        return Labels(self.world)

    def label(self, t: int) -> str:
        return self.labels.label(t)

    @cached_property
    def sim(self) -> Sim:
        """The W-1 simulator used to evaluate conditions (`holds`), one per version.

        条件評価（`holds`）に使う W-1 シミュレーター。バージョンごとに 1 つ。
        """
        return Sim(self.world)

    @cached_property
    def characters(self) -> dict[str, Json]:
        return {c["id"]: c for c in self.world["characters"]}

    @cached_property
    def roles(self) -> dict[str, Json]:
        return {r["id"]: r for r in self.world["roles"]}

    @cached_property
    def acts(self) -> dict[str, Json]:
        return {a["id"]: a for a in self.world["acts"]}

    @cached_property
    def beats(self) -> dict[str, Json]:
        return {b["id"]: b for b in self.world["beats"]}

    @cached_property
    def places(self) -> dict[str, Json]:
        return {p["id"]: p for p in self.world["places"]}

    def act_of(self, state_vars: Json) -> str:
        act: str = state_vars.get("var.act.current") or min(self.world["acts"], key=lambda a: a["order"])["id"]
        return act

    def scene_of(self, place: str, act: str) -> str:
        """Which scene the player's place belongs to: by layout if there is one, otherwise the act's first scene.

        プレイヤーのいる場所がどの場面に属するか：レイアウトがあればレイアウトで、なければこの幕の最初の場面。
        """
        for s in self.scenes.values():
            if place in s.places:
                return s.scene_id
        scenes: list[str] = self.acts[act]["scenes"]
        return scenes[0]


class Library:
    """All world models and scene layouts in the repo, read once when the process starts.

    `current` is the one new games use (`Settings.world`, i.e. `ZJ_WORLD` or the default draft); existing games look up
    their locked version with `version()`, and a version that isn't here is an error, never silently swapped.

    リポジトリにあるすべての世界モデルと場面レイアウト。プロセス起動時に 1 回読む。

    `current` は新しいゲームに使うもの（`Settings.world`、つまり `ZJ_WORLD` か既定の草稿）。既存のゲームは
    固定したバージョンを `version()` で引き、ここにないバージョンはエラーにして、黙って差し替えない。
    """

    def __init__(self, worlds: Path, scenes: Path, current: Path, released: tuple[Path, ...] = ()) -> None:
        self.layouts: dict[str, Scene] = {}
        for p in sorted(scenes.glob("*/scene.json")):
            s = Scene.read(p)
            self.layouts[s.scene_id] = s
        self.by_version: dict[str, Book] = {}
        for p in sorted(worlds.glob("*/*/world.json")):
            self._add(p)
        self.current = self._add(current)
        # The catalog is the explicit release list; finding a draft file doesn't mean it is open. Each book locks one
        # version for new games.
        # カタログは明示的な公開リスト。草稿ファイルが見つかっても公開済みとは限らない。本ごとに新規ゲーム用の
        # バージョンを 1 つだけ固定する。
        self.available: dict[str, Book] = {self.current.book_id: self.current}
        for path in released:
            book = self._add(path)
            if book.book_id in self.available:
                raise ValueError(f"Duplicate open book: {book.book_id} / 公開する本が重複：{book.book_id}")
            self.available[book.book_id] = book

    def _add(self, path: Path) -> Book:
        w = json.loads(path.read_text(encoding="utf-8"))
        book = Book(book_id=w["book"]["id"], world=w, path=path)
        existing = self.by_version.get(book.version)
        if existing is not None and existing.book_id != book.book_id:
            raise ValueError(
                f"World version reused by different books: {book.version}"
                f" / 世界バージョンが別の本で再利用されている：{book.version}"
            )
        book.scenes = {k: v for k, v in self.layouts.items() if k in {s["id"] for s in w["scenes"]}}
        self.by_version[book.version] = book
        return book

    def book(self, book_id: str) -> Book | None:
        """New games only use the explicit release list; existing games use version() and don't upgrade with the
        catalog.

        新しいゲームは明示的な公開リストだけを使う。既存のゲームは version() を使い、カタログに合わせて上げない。
        """
        return self.available.get(book_id)

    def version(self, world_model_version: str) -> Book:
        return self.by_version[world_model_version]
