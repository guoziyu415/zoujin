@router.get("/v1/playthroughs/{pid}/ending")
async def get_ending(request: Request, pid: str) -> Response:
    """2.8: 404 before the ending starts; 202 while the ending task isn't done (etaSeconds = 15 minus the seconds
    already passed, at least 5); 200 EndingView once done.

    2.8：エンディングに入る前は 404。エンディングのタスクが終わっていなければ 202（etaSeconds = 15
    から経過秒数を引いたもの、最低 5）。終わったら 200 EndingView。
    """
    gw = gw_of(request)
    await owned(request, pid)
    async with gw.engine.connect() as c:
        body = await c.scalar(select(endings.c.body).where(endings.c.playthrough_id == pid))
        if body is not None:
            return ok(gw, "ending", 200, ending_mod.view(body))
        started = await c.scalar(
            select(func.extract("epoch", func.now() - playthrough_metrics.c.ending_started_at)).where(
                playthrough_metrics.c.playthrough_id == pid
            )
        )
        queued = await c.scalar(
            select(turns.c.turn_id).where(turns.c.playthrough_id == pid, turns.c.kind == ending_mod.KIND).limit(1)
        )
    if queued is None:
        raise Fail("not_found")
    # Opening the recollection straight from the study may have no WebSocket. Reading 202 after a restart/disconnect
    # wakes the existing task; no new ending task is created: the narrator deduplicates by PostgreSQL lease and
    # idempotency key, and when the finished row exists it has already returned above.
    # 書斎から直接回想を開くときは WebSocket がないこともある。再起動・切断後に 202 を読んだら既存のタスクを起こす。
    # エンディングのタスクは新しく作らない：ナレーターが PostgreSQL のリースと冪等キーで重複を除き、
    # 完了した行があれば上ですでに返している。
    gw.kick(pid)
    elapsed = float(started) if started is not None else 0.0
    return ok(gw, "ending", 202, {"status": "pending", "etaSeconds": ending_mod.eta(0.0, elapsed)})


