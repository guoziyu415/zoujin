async def idempotent(request: Request, user_id: str, run: Callable[[], Awaitable[Response]]) -> Response:
    """Write endpoints with `Idempotency-Key` (same scheme as POST /v1/playthroughs): queued per account and key; a
    seen key with the same request gets the previous result, a different request gets idempotency_conflict. Only
    successful results are recorded (404 and 403 are not; another key is judged afresh).

    `Idempotency-Key` 付きの書き込みエンドポイント（POST /v1/playthroughs と同じ仕組み）：同じアカウント・
    同じキーは順番に処理する。見たことのあるキーで同じリクエストなら前回の結果を、違うリクエストなら
    idempotency_conflict を返す。成功した結果だけを記録する（404、403 は記録せず、別のキーならあらためて判定する）。
    """
    gw = gw_of(request)
    key = request.headers.get("idempotency-key")
    if not key or len(key) > 200:
        log.info("%s %s without Idempotency-Key / Idempotency-Key なし", request.method, request.url.path)
        raise Fail("invalid_request")
    fp = fingerprint(request, await request.body())
    async with gw.engine.begin() as lock:
        await lock.execute(LOCK_KEY, {"k": f"idem:{user_id}:{key}"})
        async with gw.engine.connect() as c:
            seen = (
                await c.execute(
                    select(
                        idempotency_keys.c.request_hash, idempotency_keys.c.status_code, idempotency_keys.c.response
                    ).where(idempotency_keys.c.user_id == user_id, idempotency_keys.c.key == key)
                )
            ).first()
        if seen is not None:
            if seen.request_hash != fp:
                raise Fail("idempotency_conflict")
            if seen.status_code == 202:
                return Response(status_code=202)
            return JSONResponse(seen.response, status_code=seen.status_code)
        resp = await run()
        if 200 <= resp.status_code < 300:
            async with gw.engine.begin() as c:
                body = bytes(resp.body) if resp.body else b"{}"
                await c.execute(
                    insert(idempotency_keys).values(
                        user_id=user_id,
                        key=key,
                        request_hash=fp,
                        status_code=resp.status_code,
                        response=json.loads(body),
                    )
                )
        return resp


async def memory_of(request: Request, endpoint: str, pid: str, memory_id: str) -> Json:
    """This undeleted memory in the playthrough (which belongs to this person); missing, deleted or an invalid ID → 404.

    （この人のものである）このプレイの削除されていないこの記憶。存在しない、削除済み、ID が不正 → 404。
    """
    gw = gw_of(request)
    await owned(request, pid)
    if gw.schemas.request_errors(endpoint, "params", {"id": pid, "memoryId": memory_id}):
        raise Fail("not_found")
    async with gw.engine.connect() as c:
        row = (
            (
                await c.execute(
                    select(memory_items).where(
                        memory_items.c.memory_id == memory_id,
                        memory_items.c.playthrough_id == pid,
                        memory_items.c.deleted_at.is_(None),
                    )
                )
            )
            .mappings()
            .first()
        )
    if row is None:
        raise Fail("not_found")
    return dict(row)


