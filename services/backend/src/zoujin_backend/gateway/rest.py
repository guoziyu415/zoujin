class Fail(Exception):
    def __init__(self, code: str, *, active: Json | None = None, retry_after: int | None = None) -> None:
        super().__init__(code)
        self.code = code
        self.active = active
        self.retry_after = retry_after


def gw_of(request: Request) -> Gateway:
    gw: Gateway = request.app.state.gw
    return gw


def error_body(gw: Gateway, code: str, active: Json | None = None, retry_after: int | None = None) -> Json:
    doc: Json = {
        "error": {
            "code": code,
            "message": MESSAGES[code],
            "retryable": code in ("rate_limited", "internal"),
            "retryAfterSeconds": retry_after,
        }
    }
    if active is not None:
        doc["activePlaythrough"] = active
    return gw.schemas.build("api/error.schema.json", "#/$defs/ErrorResponse", doc)


def fail_response(gw: Gateway, f: Fail) -> JSONResponse:
    return JSONResponse(error_body(gw, f.code, f.active, f.retry_after), status_code=STATUS[f.code])


def ok(gw: Gateway, endpoint: str, status: int, doc: Json) -> JSONResponse:
    try:
        body = gw.schemas.response(endpoint, status, doc)
    except SchemaError:
        log.exception("Not returning %s %s: breaks the contract / 契約に合わない", endpoint, status)
        return fail_response(gw, Fail("internal"))
    return JSONResponse(body, status_code=status)


async def body_of(request: Request) -> Json:
    try:
        return json.loads(await request.body() or b"null")
    except json.JSONDecodeError:
        raise Fail("invalid_request") from None


def check_request(gw: Gateway, endpoint: str, part: str, doc: Json) -> None:
    errs = gw.schemas.request_errors(endpoint, part, doc)
    if errs:
        log.info("%s %s doesn't match the Schema / Schema に合わない: %s", endpoint, part, "; ".join(errs[:3]))
        raise Fail("invalid_request")


def set_cookie(gw: Gateway, resp: Response, token: str) -> None:
    resp.set_cookie(
        COOKIE,
        token,
        max_age=SESSION_DAYS * 24 * 3600,
        httponly=True,
        samesite="lax",
        # For local http, the dev switch turns Secure off (B-0 item 3).
        # ローカルの http では開発用スイッチで Secure をオフにする（B-0 第 3 項）。
        secure=not gw.settings.dev,
        path="/",
    )


async def user_of(request: Request) -> str:
    """userId of a valid session; if it was renewed, note it on request.state so the middleware adds Set-Cookie.

    有効なセッションの userId。延長したら request.state に記録し、ミドルウェアが Set-Cookie を付け足す。
    """
    gw = gw_of(request)
    token = request.cookies.get(COOKIE)
    async with gw.engine.begin() as c:
        found = await auth.session_user(c, token)
    if found is None:
        raise Fail("unauthenticated")
    user_id, slid = found
    if slid and token:
        request.state.slid_token = token
    return user_id


async def owned(request: Request, pid: str) -> str:
    """The playthrough belongs to this person: 404 if the ID isn't a valid playthrough ID or doesn't exist, 403 if it's
    someone else's (section 5).

    このプレイがこの人のものであること：正しいプレイ ID でないかプレイが存在しなければ 404、他人のものなら 403（第 5
    節）。
    """
    gw = gw_of(request)
    user_id = await user_of(request)
    if gw.schemas.request_errors("snapshot", "params", {"id": pid}):
        raise Fail("not_found")
    async with gw.engine.connect() as c:
        owner = await c.scalar(select(playthroughs.c.user_ref).where(playthroughs.c.playthrough_id == pid))
    if owner is None:
        raise Fail("not_found")
    if owner != user_id:
        raise Fail("forbidden")
    return user_id


