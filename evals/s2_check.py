def fake_ulid(key):
    """A validly shaped ULID for test data (26 Crockford base32 characters), derived deterministically from key, so it
    does not change when the generator is rerun.

    テストデータ用の正しい形の ULID（Crockford base32 で 26 文字）。key から決定的に計算するので、生成器を再実行しても変わらない。
    """
    import hashlib
    n = int.from_bytes(hashlib.sha256(key.encode()).digest()[:15], "big")
    return "01J" + "".join(CROCKFORD[(n >> (5 * i)) & 31] for i in range(23))


def lcs_len(a, b):
    """Length of the longest common substring (compared the same way as no_verbatim_quotes: copying 8 or more
    characters of the original words counts as quoting).

    最長共通部分文字列の長さ（no_verbatim_quotes と同じ比べ方：元の発話を 8 文字以上そのまま写せば引用とみなす）。
    """
    best, prev = 0, [0] * (len(b) + 1)
    for x in a:
        cur = [0] * (len(b) + 1)
        for j, y in enumerate(b, 1):
            if x == y:
                cur[j] = prev[j - 1] + 1
                best = max(best, cur[j])
        prev = cur
    return best


class S2:
    def __init__(self, world, scenarios):
        self.w = world
        self.sim = Sim(world)
        self.ck = Checker(world, scenarios, [])
        self.scen = {"sc.canon": {"id": "sc.canon"}, **{s["id"]: s for s in scenarios}}
        self.roles = {r["id"]: r for r in world["roles"]}
        self.chars = {c["id"]: c for c in world["characters"]}
        self.facts = {f["id"]: f for f in world["facts"]}
        self.items = {x["id"]: x for x in world.get("items", [])}
        self.affs = {a["id"]: a for a in world["affordances"]}
        self.places = {p["id"]: p for p in world["places"]}
        self.anchor_beats = {b["id"] for b in world["beats"] if b["kind"] == "anchor"} | \
            {a for a in world["anchors"] if a.startswith("beat.")}
        self.ids = set(self.chars) | set(self.facts) | set(self.items) | set(self.affs) | set(self.places) | \
            set(self.sim.beats) | set(self.sim.svars) | set(self.roles) | set(self.scen) | \
            {a["id"] for c in world["characters"] for a in c.get("mutualAid", [])} | \
            {p["id"] for c in world["characters"] for p in c.get("promiseTemplates", [])} | \
            {g["id"] for g in world["globalRules"]} | \
            {v["id"] for b in world["beats"] for v in b.get("variants", [])}

    # ---------- checkpoint / チェックポイント ----------
    def state_at(self, setup):
        """Simulate the scenario up to the checkpoint, then apply setup.events. Returns (res, learned, granted, err).

        シナリオをチェックポイントまでシミュレーションし、setup.events を適用する。(res, learned, granted, err) を返す。
        """
        role = self.roles.get(setup.get("role"))
        if not role or role.get("release") != 1:
            return None, None, None, f"role does not exist or is not in release 1 / 役割が存在しないか第一版にない：{setup.get('role')}"
        m = re.fullmatch(r"(sc\.[\w-]+)@(?:(beat\.[\w-]+)|t=(\d+))", setup.get("checkpoint", ""))
        if not m or m[1] not in self.scen or (m[2] and m[2] not in self.sim.beats):
            return None, None, None, f"bad checkpoint / チェックポイントが不正：{setup.get('checkpoint')}"
        res = self.sim.run(self.scen[m[1]], ("beat", m[2]) if m[2] else ("t", int(m[3])),
                           role=role["id"], place=setup.get("place"))
        if not res["stopped"]:
            return None, None, None, f"{m[2]} does not happen in {m[1]} / {m[2]} は {m[1]} で起きない"
        if res["t"] < role["startT"]:
            return None, None, None, (f"checkpoint t={res['t']} is before the role's start {role['startT']}"
                                      f" / チェックポイント t={res['t']} が役割の開始 {role['startT']} より前")
        # Public facts of beats that happened while the player was present (contract 2.1, 1.7): the same rule as B-2,
        # taken from opening() in the shared library.
        # プレイヤーがその場にいたときに起きたビートの public な事実（契約 2.1、1.7）：B-2 と同じ規則で、共有ライブラリの
        # opening() から取る。
        until = ("beat", m[2]) if m[2] else ("t", int(m[3]))
        seen = opening(self.w, role["id"], self.scen[m[1]], until, place=setup.get("place"))[1]["knowledge"]
        learned, granted = {"player": set(seen.get("player", []))}, set()
        for ev in setup.get("events", []):
            for e in ev.get("effects", []):
                if e.get("op") == "learn":
                    learned.setdefault(e["character"], set()).add(e["fact"])
                if e.get("op") == "set" and e.get("var") == "var.player.location":
                    granted.add(e["value"])
            self.sim.apply(ev.get("effects", []), res["state"], res["where"])
        return res, learned, granted, None

    def reach(self, role, state, granted):
        ok = set(role["access"]) | granted
        return ok | {ca["place"] for ca in role.get("conditionalAccess", []) if self.sim.holds(ca["when"], state)}

    def occurred(self, b, res):
        return b == "pre" or res["status"].get(b) in OCCURRED

    def fact_true(self, f, res):
        return self.occurred(self.facts[f]["trueFrom"], res)

    def knows(self, actor, fact, res, learned, role):
        if not self.fact_true(fact, res):
            return False
        if fact in learned.get(actor, set()):
            return True
        if actor == "player":
            return fact in role.get("initialKnowledge", [])
        return any(k["fact"] == fact and self.occurred(k["since"], res) for k in self.chars[actor]["knows"])

    def dist(self, a, b):
        """R3 distances use travel_minutes from the shared rule library (moving within one scene takes 0 minutes,
        S-038); unreachable counts as infinitely far.

        R3 の道のりは共有規則ライブラリの travel_minutes を使う（同じシーン内の移動は 0 分、S-038）。行けない場合は無限に遠いとみなす。
        """
        d = travel_minutes(self.w, a, b)
        return 10 ** 9 if d is None else d

    def anchor_locked(self, res):
        """Variables written by an anchor beat that has happened and not changed by any later beat → their values
        (overturning one = R1).

        起きた錨（anchor）ビートが書き、その後どのビートも変えていない変数 → その値（覆せば R1）。
        """
        locked = {}
        for bid in sorted(res["times"], key=lambda b: (res["times"][b], self.sim.beats[b]["order"])):
            if res["status"].get(bid) not in OCCURRED:
                continue
            for e in self.sim.beats[bid]["outcomes"]:
                if e["op"] != "set":
                    continue
                if bid in self.anchor_beats:
                    locked[e["var"]] = e["value"]
                else:
                    locked.pop(e["var"], None)
        return {v: x for v, x in locked.items() if res["state"].get(v) == x}

    # ---------- the simplest deterministic judgement / 最も簡単な決定的判定 ----------
    def judge(self, item):
        """Returns (set of reported rules, list of reasons, list of errors). An error = the label itself is broken (not
        a rule verdict).

        (報告した規則の集合, 理由のリスト, エラーのリスト) を返す。エラー = そのラベル自体が壊れている（規則の判定ではない）。
        """
        setup, turn, c = item["setup"], item.get("turn", {}), item["candidate"]
        role = self.roles.get(setup.get("role"))
        res, learned, granted, e0 = self.state_at(setup)
        if e0:
            return set(), [], [e0]
        state, where, clock = res["state"], res["where"], res["t"]
        ppl = state["var.player.location"]
        errs, hits, why = [], set(), []

        def hit(rule, msg):
            hits.add(rule)
            why.append(f"{rule}：{msg}")

        if ppl not in self.reach(role, state, granted):
            errs.append(f"the player is at {ppl}, which {role['id']} cannot enter now (arrange it with setup.events)"
                        f" / プレイヤーは {ppl} にいるが、{role['id']} は今そこに入れない（setup.events で用意する）")
        to = turn.get("to")
        if to and to not in self.chars:
            errs.append(f"turn.to does not exist / turn.to が存在しない {to}")
        elif to and state["var.player.companionOf"] != to and where.get(to) != ppl:
            errs.append(f"{to} is at {where.get(to)} and the player at {ppl}, so they cannot talk"
                        f" / {to} は {where.get(to)}、プレイヤーは {ppl} にいて話せない")
        if c["place"] not in self.places:
            errs.append(f"candidate.place does not exist / candidate.place が存在しない {c['place']}")
        actor = c["actor"]
        if actor != "player" and actor not in self.chars:
            errs.append(f"actor does not exist / actor が存在しない {actor}")
        if errs:
            return hits, why, errs

        # R3: time only moves forward / R3：時間は前にしか進まない
        if c["t"] < clock:
            hit("R3-time", f"t={c['t']} is before the current clock {clock} (time cannot go backwards,"
                           f" rule.time-moves-forward) / t={c['t']} が現在の時計 {clock} より前（時間は戻せない、"
                           f"rule.time-moves-forward）")

        sim_state = dict(state)
        for e in c["effects"]:
            op = e["op"]
            if op == "beat":
                b, st = e["beat"], res["status"].get(e["beat"])
                if b in self.anchor_beats and e["to"] != "happened":
                    hit("R1-anchor", f"{b} is an anchor and cannot be {e['to']} / {b} は錨なので {e['to']} にできない")
                if st is not None:
                    hit("R2-precondition", f"{b} already has a result ({st}) and cannot be {e['to']} again"
                                           f" / {b} にはすでに結果がある（{st}）ので、もう {e['to']} にできない")
                elif e["to"] in OCCURRED:
                    # W-1's check_effects reports this too (backend 2026-10-10) / W-1 の check_effects も同様に報告する（バックエンド 2026-10-10）
                    if e["to"] == "happened":
                        hit("R2-precondition", f"{b}: only the system event at the scheduled time writes happened; a"
                                               f" candidate event that brings it forward uses hastened (contract 2.4.1)"
                                               f" / {b}：happened を書くのは予定時刻のシステムイベントだけ。候補イベントで"
                                               f"早めるなら hastened を使う（契約 2.4.1）")
                    bb = self.sim.beats[b]
                    if not self.sim.holds(bb["preconditions"], sim_state):
                        hit("R2-precondition", f"the preconditions of {b} do not hold / {b} の前提が成り立たない"
                                               f" {bb['preconditions']}")
                    if any(res["status"].get(f) not in OCCURRED for f, ty, _ in self.sim.parents[b] if ty == "requires"):
                        hit("R2-precondition", f"a beat required before {b} has not happened yet"
                                               f" / {b} に必要な前のビートがまだ起きていない")
            elif op == "set":
                v = e["var"]
                locked = self.anchor_locked(res)
                if v in locked and e["value"] != locked[v]:
                    hit("R1-anchor", f"{v} = {locked[v]!r} is the result of an anchor beat and cannot be changed to"
                                     f" {e['value']!r} / {v} = {locked[v]!r} は錨ビートの結果なので {e['value']!r} に変えられない")
                if v in TERMINAL and sim_state.get(v) == TERMINAL[v] and e["value"] != TERMINAL[v]:
                    hit("R2-precondition", f"{v} is already {TERMINAL[v]}; the dead do not come back"
                                           f" (rule.no-resurrection) / {v} はすでに {TERMINAL[v]}。死者は生き返らない"
                                           f"（rule.no-resurrection）")
                if v == "var.player.location":
                    if e["value"] not in self.reach(role, sim_state, set()):
                        hit("R7-capability", f"{role['id']} cannot enter {e['value']} (access and the conditionalAccess"
                                             f" that holds now) / {role['id']} は {e['value']} に入れない（access と"
                                             f"今成り立つ conditionalAccess）")
                    d = self.dist(ppl, e["value"])
                    if d > c["dt"]:
                        hit("R3-time", f"the player needs at least {d} min from {ppl} to {e['value']}, the event"
                                       f" only gives {c['dt']} min / プレイヤーは {ppl} から {e['value']} まで少なくとも"
                                       f" {d} 分かかるが、イベントは {c['dt']} 分しかない")
            elif op == "relocate":
                ch, frm = e["character"], where.get(e["character"])
                if any(state.get(v) == TERMINAL[v] for v in TERMINAL if v == "var.hostage.fate") and \
                        state.get("var.hostage.who") == ch:
                    hit("R2-precondition", f"{ch} has already been executed; the dead do not come back"
                                           f" / {ch} はすでに処刑された。死者は生き返らない")
                d = self.dist(frm, e["place"]) if frm else 0
                if d > c["dt"]:
                    hit("R3-time", f"{ch} needs at least {d} min from {frm} to {e['place']}, the event only gives"
                                   f" {c['dt']} min / {ch} は {frm} から {e['place']} まで少なくとも {d} 分かかるが、"
                                   f"イベントは {c['dt']} 分しかない")
            elif op == "learn":
                f = e["fact"]
                if not self.fact_true(f, res):
                    hit("R4-knowledge", f"{f} does not hold yet (trueFrom {self.facts[f]['trueFrom']} has not happened)"
                                        f" / {f} はまだ成り立たない（trueFrom {self.facts[f]['trueFrom']} が起きていない）")
                elif not self.knows(actor, f, res, learned, role):
                    hit("R4-knowledge", f"{actor} does not know {f} now / {actor} は今 {f} を知らない")
            elif op == "improv":
                ch = e["character"]
                for fid, f in self.facts.items():
                    terms = [x for x in f.get("spoilerTerms") or [] if x in e["statement"]]
                    if terms and not self.knows(ch, fid, res, learned, role):
                        hit("R4-knowledge", f"the improvised detail contains spoiler terms {terms} of {fid}, which {ch}"
                                            f" does not know now / 即興の設定に {fid} のネタバレ語 {terms} があるが、"
                                            f"{ch} は今それを知らない")
            elif op == "hold" and actor == "player":
                if sim_state.get(e["item"]) != "player":
                    hit("R7-capability", f"{e['item']} is not in the player's hands (it is now with"
                                         f" {sim_state.get(e['item'])}) / {e['item']} はプレイヤーの手にない"
                                         f"（今は {sim_state.get(e['item'])}）")
                tgt = e.get("to")
                if tgt not in (None, "player") and where.get(tgt) != ppl and state["var.player.companionOf"] != tgt:
                    hit("R7-capability", f"{tgt} is at {where.get(tgt)} and the player at {ppl}, so it cannot be"
                                         f" handed over / {tgt} は {where.get(tgt)}、プレイヤーは {ppl} にいて手渡せない")
            # Contract 1.6 (C-16) StateVar.valueRequires: the king's heart (trust 40 / 70), crossing by the bridge (the
            # bridge still standing) and so on; read only from the world model.
            # 契約 1.6（C-16）StateVar.valueRequires：王の心（信頼 40 / 70）、橋での渡河（橋がまだある）など。世界モデルだけを読む。
            for x in self.sim.value_requires([e], sim_state):
                now = {cnd["var"]: sim_state.get(cnd["var"]) for cnd in x["when"]}
                hit("R2-precondition", f"{x['var']} = {x['value']!r} needs {x['when']}, now {now} ({x['note']})"
                                       f" / {x['var']} = {x['value']!r} には {x['when']} が必要、今は {now}（{x['note']}）")
            self.sim.apply([e], sim_state, None)

        act = turn.get("act")
        if act and act.get("affordance"):
            a = self.affs.get(act["affordance"])
            if not a:
                errs.append(f"action does not exist / アクションが存在しない {act['affordance']}")
            else:
                if a["place"] != ppl:
                    hit("R7-capability", f"{a['id']} can only be done at {a['place']}, the player is at {ppl}"
                                         f" / {a['id']} は {a['place']} でしかできないが、プレイヤーは {ppl} にいる")
                if a.get("roles") and role["id"] not in a["roles"]:
                    hit("R7-capability", f"{a['id']} can only be done by {a['roles']} / {a['id']} は {a['roles']} だけができる")
                if a.get("when") and not self.sim.holds(a["when"], state):
                    hit("R7-capability", f"the condition of {a['id']} does not hold now / {a['id']} の条件が今成り立たない"
                                         f" {a['when']}")
                it = self.items.get(a.get("item"))
                if it and not it.get("portable") and ppl not in it.get("at", []):
                    hit("R7-capability", f"{a['id']} needs {it['id']}, which is not here / {a['id']} には {it['id']}"
                                         f" が必要だが、ここにはない")
        return hits, why, errs

    # ---------- format / 形式 ----------
    def check_item(self, item, where):
        errs = []
        for k in set(item) - ITEM_KEYS:
            errs.append(f"{where}: unknown field / 不明なフィールド {k}")
        c, lb, turn = item.get("candidate", {}), item.get("label", {}), item.get("turn", {})
        for k in set(c) - CAND_KEYS:
            errs.append(f"{where}: unknown candidate field / candidate の不明なフィールド {k}")
        for k in set(lb) - LABEL_KEYS:
            errs.append(f"{where}: unknown label field / label の不明なフィールド {k}")
        for k in set(turn) - TURN_KEYS:
            errs.append(f"{where}: unknown turn field / turn の不明なフィールド {k}")
        if not (turn.get("player") or turn.get("act")):
            errs.append(f"{where}: turn needs the player's words or an action / turn にはプレイヤーの発話かアクションが必要")
        if c.get("type") not in EVENT_TYPES or c.get("origin") not in ORIGINS:
            errs.append(f"{where}: invalid type or origin / type か origin が不正: {c.get('type')} / {c.get('origin')}")
        if not isinstance(c.get("dt"), int) or c["dt"] < 0:
            errs.append(f"{where}: dt must be a non-negative integer / dt は 0 以上の整数であること")
        if not JA.search(c.get("summary", "")):
            errs.append(f"{where}: summary must be Japanese / summary は日本語であること")
        for x in c.get("causes", []):
            if x not in self.sim.beats:
                errs.append(f"{where}: beat in causes does not exist / causes のビートが存在しない {x}")
        if c.get("beneficiary") not in (None, "player") and c["beneficiary"] not in self.chars:
            errs.append(f"{where}: bad beneficiary / beneficiary が不正")
        n0 = len(self.ck.errors)
        self.ck.check_effects(c.get("effects", []), where)
        errs += self.ck.errors[n0:]
        del self.ck.errors[n0:]
        for e in c.get("effects", []):
            if e.get("op") == "improv" and not (RF_ID.match(str(e.get("factId", ""))) and JA.search(e.get("statement", ""))):
                errs.append(f"{where}: improv needs a factId of the form rf_ + ULID (use fake_ulid) and a Japanese"
                            f" statement / improv には「rf_ + ULID」形式の factId（fake_ulid を使う）と日本語の statement が必要")
        v, fr, aa = lb.get("verdict"), lb.get("failedRules", []), lb.get("acceptAlso", [])
        if v not in ("pass", "fail"):
            errs.append(f"{where}: verdict must be pass or fail / verdict は pass か fail のみ")
        if any(r not in RULES for r in fr + aa):
            errs.append(f"{where}: bad rule names / 規則名が不正 {fr + aa}")
        if v == "pass" and (fr or aa or lb.get("stage") or lb.get("fix")):
            errs.append(f"{where}: a compliant item has no failedRules, acceptAlso, stage or fix"
                        f" / 合格のものには failedRules、acceptAlso、stage、fix を書かない")
        if v == "fail":
            if not fr:
                errs.append(f"{where}: a violation needs failedRules / 違反には failedRules を書く")
            if lb.get("stage") not in ("rules", "model"):
                errs.append(f"{where}: a violation's stage must be rules or model / 違反の stage は rules か model のみ")
            elif lb["stage"] == "rules" and fr and fr[0] not in DET_RULES:
                errs.append(f"{where}: main rule {fr[0]} is not deterministic, so stage cannot be rules"
                            f" / 主規則 {fr[0]} は決定的な規則ではないので、stage を rules にできない")
            if not lb.get("fix"):
                errs.append(f"{where}: a violation needs fix (how to rewrite, downgrade or reject it correctly)"
                            f" / 違反には fix を書く（どう書き換え、格下げ、却下すれば正しいか）")
            if set(fr) & set(aa):
                errs.append(f"{where}: acceptAlso must not repeat failedRules / acceptAlso は failedRules と重複させない")
        if not lb.get("rationale") or not lb.get("refs"):
            errs.append(f"{where}: rationale and refs are required / rationale と refs を書く")
        for r in lb.get("refs", []):
            if r not in self.ids:
                errs.append(f"{where}: ID in refs does not exist / refs の ID が存在しない {r}")
        for t in item.get("tags", []):
            if t not in TAGS:
                errs.append(f"{where}: unknown tag / 不明な tag {t}")
        # A summary only describes actions in the story: it does not copy the player's words and holds no personal
        # information (a violation is R6), unless that is exactly what the item tests.
        # 要約は物語の中の行動だけを書く：プレイヤーの発話を写さず、個人情報を含まない（違反は R6）。その件がまさにそれを
        # テストする場合を除く。
        tags = set(item.get("tags", []))
        said = turn.get("player", "")
        if said and "verbatim-quote" not in tags and lcs_len(said, c.get("summary", "")) >= 8:
            errs.append(f"{where}: summary copies 8 or more characters of the player's words (rewrite it unless the item"
                        f" tests R6) / summary がプレイヤーの発話を 8 文字以上写している（R6 をテストする件でなければ書き直す）")
        texts = [turn.get("player", ""), turn.get("reply", ""), c.get("summary", "")] + \
            [e.get("statement", "") + e.get("text", "") for e in c.get("effects", [])]
        if "pii" not in tags and any(PII.search(x) for x in texts):
            errs.append(f"{where}: contains a string that looks like a phone number, email or postal code (only allowed in"
                        f" pii items) / 電話番号、メール、郵便番号のような文字列がある（pii の件でのみ可）")
        if errs:
            return errs
        hits, why, jerr = self.judge(item)
        if jerr:
            return [f"{where}：{x}" for x in jerr]
        if v == "fail" and lb["stage"] == "rules":
            if fr[0] not in hits:
                errs.append(f"{where}: a violation labelled rules, but the judgement did not report the main rule {fr[0]}"
                            f" (it reported {sorted(hits)}) / rules とラベル付けした違反だが、判定が主規則 {fr[0]} を報告"
                            f"しなかった（報告したのは {sorted(hits)}）")
            extra = hits - set(fr) - set(aa)
            if extra:
                errs.append(f"{where}: the judgement reported extra rules / 判定が余分に報告した {sorted(extra)}: {why}")
        elif hits:
            kind = "a compliant item / 合格の件" if v == "pass" else "an item labelled model / model とラベル付けした件"
            errs.append(f"{where}: {kind} was reported by the deterministic judgement / 決定的判定に報告された {why}")
        return errs


def load(path):
    return [json.loads(x) for x in Path(path).read_text(encoding="utf-8").splitlines() if x.strip()]


def fill_t(items, world_path=WORLD, scen_path=SCENARIOS):
    """An omitted candidate.t = the checkpoint's clock. Called by the generators.

    candidate.t を省略した場合 = チェックポイントの時計。生成器から呼ぶ。
    """
    s2 = S2(json.loads(Path(world_path).read_text(encoding="utf-8")), json.loads(Path(scen_path).read_text(encoding="utf-8")))
    for it in items:
        if "t" not in it["candidate"]:
            res, _, _, err = s2.state_at(it["setup"])
            if err:
                raise SystemExit(f"{it['id']}：{err}")
            it["candidate"] = {"t": res["t"], **it["candidate"]}
    return items


def check_all(items, world_path=WORLD, scen_path=SCENARIOS):
    world = json.loads(Path(world_path).read_text(encoding="utf-8"))
    scen = json.loads(Path(scen_path).read_text(encoding="utf-8"))
    s2 = S2(world, scen)
    errs, seen = [], set()
    for it in items:
        if it.get("id") in seen:
            errs.append(f"duplicate id / id が重複 {it.get('id')}")
        seen.add(it.get("id"))
        errs += s2.check_item(it, it.get("id", "?"))
    return s2, errs


def scope_gap(items):
    """backend-design v1.0.9 2.4: step 4 (the model check) runs on every candidate event that passed step 3 and has
    non-empty effects; the rule part of R6 (patterns for phone numbers, emails and addresses, and 8 consecutive
    characters identical to the original words) runs on every summary in step 3.
    Violations labelled model whose effects are empty and which are not one of these two R6 kinds → within this scope
    they reach no check at all.

    backend-design v1.0.9 2.4：ステップ 4（モデルのチェック）は、ステップ 3 を通過し effects が空でない候補イベントすべてに
    実行する。R6 の規則部分（電話、メール、住所のパターン、元の発話と連続 8 文字が同じ）はステップ 3 ですべての要約に実行する。
    model とラベル付けした違反のうち、effects が空で、この二種類の R6 でもないもの → この範囲ではどのチェックにも届かない。
    """
    def r6_rules(it):
        return it["label"]["failedRules"][0] == "R6-safety" and {"pii", "verbatim-quote"} & set(it.get("tags", []))
    return [it["id"] for it in items if it["label"]["verdict"] == "fail" and it["label"]["stage"] == "model"
            and not it["candidate"]["effects"] and not r6_rules(it)]


def summary(items):
    from collections import Counter
    fails = [i for i in items if i["label"]["verdict"] == "fail"]
    by = Counter(i["label"]["failedRules"][0] for i in fails)
    st = Counter(i["label"]["stage"] for i in fails)
    rules = ", ".join(f"{r.split('-')[0]} {by[r]}" for r in RULES if by[r])
    gap = len(scope_gap(items))
    return (f"{len(items)} items: {len(fails)} violations ({rules}; {st['rules']} detectable by rules,"
            f" {st['model']} need the meaning understood), {len(items) - len(fails)} compliant; {gap} violations missed"
            f" within the step-4 scope (backend-design v1.0.9)"
            f" / {len(items)} 件：違反 {len(fails)}（{rules.replace(', ', '、')}；規則で判定できる {st['rules']}、"
            f"意味の理解が必要 {st['model']}）、合格 {len(items) - len(fails)}；"
            f"ステップ 4 の範囲（backend-design v1.0.9）で見逃される違反 {gap} 件")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("path")
    ap.add_argument("--world", default=str(WORLD))
    ap.add_argument("--scenarios", default=str(SCENARIOS))
    a = ap.parse_args()
    items = load(a.path)
    _, errs = check_all(items, a.world, a.scenarios)
    for e in errs:
        print("error / エラー：" + e)
    print(summary(items) + f"; errors {len(errs)} / エラー {len(errs)}")
    sys.exit(1 if errs else 0)


if __name__ == "__main__":
    main()
