"""Labelled sets for the S-2 narrator self-check accuracy: format self-check + a reference judgement of the deterministic
rules (no model calls).

There are two labelled sets, written the same way:
- evals/s2/s2_dev.jsonl (public, 10 items): for the backend to build the S-2 runner and check the format; generated by
  gen_s2_dev.py;
- evals/holdout/s2/s2_holdout.jsonl (measurement set, 50 items): the backend does not look at it before the narrator
  self-check prompt is finalized (the lesson of S-069); generated by gen_s2_holdout.py in the same directory.

One item = a checkpoint + this turn (the player's words and the character's reply, or the player's action) + one
candidate event extracted by the narrator + a human label.
Under test are the narrator's steps 3 and 4 (backend-design 2.4: deterministic R1〜R4, R7; model R5, R6): given the
candidate event, it judges pass or fail and reports which rules.

`judge()` here is the **simplest deterministic judgement** written by Data, used only to check that the labels are
self-consistent:
- for a violation labelled stage = "rules", the judgement must report the first entry of label.failedRules (the main
  rule), and every rule it reports must be in failedRules ∪ acceptAlso;
- for compliant items, and for violations with stage = "model" (only detectable by understanding the meaning), the
  judgement must not report a single rule; otherwise the label is wrong, or the item can in fact be judged by rules.
It is not the backend's implementation; the backend implements the rule table in contracts section 3. How to write the
judgement: see "the simplest judgement of the deterministic rules" in evals/s2/README.md.

Usage: python3 -I evals/s2_check.py <labelled set .jsonl> (for the default world model and scenarios see --world,
--scenarios)
Standard library only.

S-2 ナレーターのセルフチェック精度のラベル付きセット：形式のセルフチェック + 決定的な規則の参照判定（モデルは呼ばない）。

ラベル付きセットは二つあり、書き方は同じ：
- evals/s2/s2_dev.jsonl（公開、10 件）：バックエンドが S-2 のランナーを組み、形式を確認するためのもの。gen_s2_dev.py で生成。
- evals/holdout/s2/s2_holdout.jsonl（測定セット、50 件）：ナレーターのセルフチェックのプロンプトが確定するまでバックエンドは
  見ない（S-069 の教訓）。同じディレクトリの gen_s2_holdout.py で生成。

1 件 = チェックポイント 1 つ + このターン（プレイヤーの発話と人物の返答、またはプレイヤーのアクション）+ ナレーターが
抽出した候補イベント 1 つ + 人手のラベル。
テスト対象はナレーターのステップ 3、4（backend-design 2.4：決定的な R1〜R4、R7、モデルの R5、R6）：候補イベントを渡すと、
合格か不合格かを判定し、どの規則かを報告する。

ここの `judge()` はデータ側が書いた**最も簡単な決定的判定**で、ラベルが自己矛盾していないかの確認にだけ使う：
- stage = "rules" とラベル付けした違反では、判定は label.failedRules の先頭（主規則）を必ず報告し、報告する規則はすべて
  failedRules ∪ acceptAlso に含まれていなければならない。
- 合格のもの、および stage = "model" の違反（意味を理解しないと判定できないもの）では、判定は規則を一つも報告してはならない。
  報告した場合は、ラベルの書き間違いか、その件は実は規則で判定できるということ。
これはバックエンドの実装ではない。バックエンドは contracts 第 3 節の規則表に従って実装する。判定の書き方は
evals/s2/README.md「決定的な規則の最も簡単な判定」を参照。

使い方：python3 -I evals/s2_check.py <ラベル付きセット.jsonl>（既定の世界モデルとシナリオは --world、--scenarios を参照）
標準ライブラリのみを使う。
"""
