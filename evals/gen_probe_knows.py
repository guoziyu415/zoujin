"""Generates evals/probes/s3_probe_knows.json: for each scenario of the anti-spoiler probes (both sets), who the
character is "at this moment" and what they know (PM S-086 ⑥).
Neither judge in the S-068 retest looks at what the character knows at the moment, so they cannot spot "moments mixed
up" (the identity or situation of a later moment leaking into an earlier one). The next retest hands this file to the
judge: the character's answer may only use what is in knows; things in notYet are only learned later, and treating
them as already known in an answer counts as overstepping.

  uv run python -I evals/gen_probe_knows.py evals/probes/s3_probe_knows.json

Everything is cut from the world model (world.json of 1.0.0-draft) by each scenario's after, nothing is hand-written:
- now: the character's summary (only what holds from the opening, contract 2.1), plus the traits and goals that hold
  at this moment (since has happened, until has not happened yet).
- knows: facts in the character's knows whose since has happened (the same rule as worldsim's knows() and
  check_probes: compare by beat order, pre is earliest), and whose trueFrom has also happened.
- notYet: facts in the character's knows whose since has not happened yet (learned later).
Standard library only.

evals/probes/s3_probe_knows.json を生成する：ネタバレ防止プローブ（両セット）の各シナリオで、この人物が「この時点」で
どんな人で、何を知っているか（PM S-086 ⑥）。
S-068 の再テストの二種類の判定はどちらも人物がこの時点で知っていることを見ないので、「時点が混ざる」（後の時点の身分や
状況が前の時点に漏れる）ことに気づけない。次の再テストではこのファイルを判定に渡す：人物の答えに使えるのは knows に
あることだけ。notYet にあることは後で知ることで、答えの中で既に知っているものとして扱えば逸脱とみなす。

すべて世界モデル（1.0.0-draft の world.json）からシナリオの after で切り出し、手書きしない：
- now：人物の summary（開局から成り立つことだけ、契約 2.1）に、この時点で成り立つ traits、goals（since が起き、until が
  まだ起きていない）を加える。
- knows：人物の knows のうち since が起きた事実（worldsim の knows()、check_probes と同じ判定：ビートの order で比べ、
  pre が最も早い）。事実の trueFrom も起きていること。
- notYet：人物の knows のうち since がまだ起きていない事実（後で知る）。
標準ライブラリのみを使う。"""

import json
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parents[1]
WORLD = DATA / "worlds" / "hashire-merosu" / "1.0.0-draft" / "world.json"
PROBES = [DATA / "evals" / "probes" / "s3_spoiler_probes.json", DATA / "evals" / "probes" / "s3_spoiler_probes_2.json"]

ABOUT = (
    "For each scenario of the anti-spoiler probes (evals/probes/s3_spoiler_probes.json and set 2"
    " s3_spoiler_probes_2.json), who the character is at this moment and what they know (PM S-086 ⑥)."
    " Generated by evals/gen_probe_knows.py from world model 1.0.0-draft by each scenario's after; do not edit by hand."
    " How judging uses it: the identity and situation the character states in an answer must match now; only things in"
    " knows may be treated as known; treating something in notYet as already known (saying they knew it all along,"
    " confirming it is true, carrying on with it as a premise) counts as knowledge overreach or mixed-up moments."
    " Taking something the player just said as heard for the first time (「そうですか」「初めて聞きました」, asking"
    " further about it) does not count; only saying they knew it all along, or adding details the player did not say,"
    " counts (the split used in the S-068 manual review, UX #87 review)."
    " / ネタバレ防止プローブ（evals/probes/s3_spoiler_probes.json と第二セット s3_spoiler_probes_2.json）の各シナリオで、"
    "人物がこの時点でどんな人で、何を知っているか（PM S-086 ⑥）。"
    "evals/gen_probe_knows.py が世界モデル 1.0.0-draft からシナリオの after で生成する。手で編集しない。"
    "判定での使い方：答えの中で人物が言う身分や状況は now と合っていなければならない。知っているものとして扱えるのは"
    " knows にあることだけ。notYet にあることを既に知っているものとして扱えば（もともと知っていたと言う、本当だと認める、"
    "前提として話を続ける）、知識の逸脱または時点の混同とみなす。"
    "プレイヤーが今言ったことを、人物が初めて聞いたこととして受け取る（「そうですか」「初めて聞きました」、そのまま問い返す）"
    "のは含めない。もともと知っていたと言う、またはプレイヤーが言っていない細部を付け足したときだけ数える"
    "（S-068 の人手による再確認の分け方、UX #87 のレビュー）。"
)


def build(world, probes):
    beats = {b["id"]: b for b in world["beats"]}
    facts = {f["id"]: f for f in world["facts"]}
    chars = {c["id"]: c for c in world["characters"]}
    places = {p["id"]: p for p in world["places"]}

    def rank(ref):
        return 0.0 if ref == "pre" else float(beats[ref]["order"])

    def active(entries, r):
        return [
            e["text"]
            for e in entries
            if rank(e.get("since", "pre")) <= r and ("until" not in e or r < rank(e["until"]))
        ]

    out = {}
    for s in probes["scenarios"]:
        c = chars[s["character"]]
        r = rank(s["after"])
        known, later = [], []
        for k in c.get("knows", []):
            f = facts[k["fact"]]
            row = {"fact": f["id"], "statement": f["statement"]}
            if rank(k["since"]) <= r and rank(f["trueFrom"]) <= r:
                known.append(row)
            else:
                later.append({**row, "since": k["since"]})
        out[s["id"]] = {
            "character": c["id"],
            "name": c["name"],
            "after": s["after"],
            "afterTitle": "原作の始まり" if s["after"] == "pre" else beats[s["after"]]["title"],
            "when": s["when"],
            "place": places[s["place"]]["name"],
            "now": {
                "summary": c["summary"],
                "traits": active(c.get("traits", []), r),
                "goals": active(c.get("goals", []), r),
            },
            "knows": known,
            "notYet": later,
        }
    return {"about": ABOUT, "worldModelVersion": world["worldModelVersion"], "scenarios": out}


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_probe_knows.py <output json> / 使い方：gen_probe_knows.py <出力する json>")
    world = json.loads(WORLD.read_text(encoding="utf-8"))
    scenarios = [s for p in PROBES for s in json.loads(p.read_text(encoding="utf-8"))["scenarios"]]
    doc = build(world, {"scenarios": scenarios})
    Path(sys.argv[1]).write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"{len(doc['scenarios'])} scenarios → {sys.argv[1]} / シナリオ {len(doc['scenarios'])} 個 → {sys.argv[1]}")


if __name__ == "__main__":
    main()
